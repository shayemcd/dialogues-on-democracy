#' Save a results table to Word, LaTeX, HTML, or CSV
#'
#' The format follows the file extension:
#' * `.docx`: Word table (also the best route into Google Docs: upload the file
#'   to Drive and open it with Google Docs, or copy the table from Word).
#' * `.tex`: booktabs LaTeX float for Overleaf; `\input{}` it from your document.
#' * `.html`: standalone page; open it in a browser, select the table, and
#'   paste into Google Docs or an email.
#' * `.csv`: the formatted cells, for anything else.
#'
#' Report text from [cr_report()] saves to `.tex` (for `\input{}` in
#' Overleaf), `.md`, `.html` (open in a browser and paste into Google Docs to
#' keep italics), or `.txt`. A [cr_ground_truth()] saves to `.json`, `.md`, or
#' `.csv`.
#'
#' A ggplot (e.g. from [cr_plot_means()]) saves as a figure: `.pdf` (vector,
#' fonts embedded), `.svg`, `.eps`, `.png`, or `.tiff` (600 dpi). Pass
#' `width = "1col"`, `"1.5col"` (default), `"2col"`, or a width in mm, and
#' optionally `height` in mm.
#'
#' @param x A `clean_results`, `cr_table`, `cr_text`, `cr_ground_truth`, or
#'   ggplot object. Pass a `cr_table` to control the table style, e.g.
#'   `cr_save(cr_table(res, style = "se"), "t2.tex")`.
#' @param path Output file path.
#' @param caption Table caption (LaTeX and Word/HTML).
#' @param label LaTeX `\label{}` key, e.g. `"tab:main"`.
#' @param landscape Word only: put the table on a landscape page.
#' @param ... Passed to [cr_flextable()] (Word/HTML) or [cr_latex()] (LaTeX).
#' @return `path`, invisibly.
#' @export
cr_save <- function(x, path, caption = NULL, label = NULL, landscape = FALSE, ...) {
  ext <- tolower(tools::file_ext(path))
  dir <- dirname(path)
  if (!dir.exists(dir)) dir.create(dir, recursive = TRUE)
  if (inherits(x, "ggplot")) {
    save_plot(x, path, ...)
    return(invisible(path))
  }
  if (inherits(x, "cr_text")) {
    save_text(x, path)
    return(invisible(path))
  }
  if (inherits(x, "cr_ground_truth")) {
    write_ground_truth(x, path)
    return(invisible(path))
  }
  tbl <- as_cr_table(x)

  switch(ext,
    docx = {
      ft <- cr_flextable(tbl, ...)
      if (!is.null(caption)) ft <- flextable::set_caption(ft, caption)
      sect <- if (landscape) {
        officer::prop_section(page_size = officer::page_size(orient = "landscape"))
      } else NULL
      flextable::save_as_docx(ft, path = path, pr_section = sect)
    },
    html = , htm = {
      ft <- cr_flextable(tbl, ...)
      if (!is.null(caption)) ft <- flextable::set_caption(ft, caption)
      flextable::save_as_html(ft, path = path)
    },
    tex = {
      writeLines(c(
        "% Generated by cleanresults. Preamble needs:",
        "% \\usepackage{booktabs}",
        "% \\usepackage{threeparttable}",
        cr_latex(tbl, caption = caption, label = label, ...)
      ), path, useBytes = TRUE)
    },
    csv = {
      m <- grid_matrix(tbl$grid)
      g <- tbl$grid
      header <- if (!is.null(g$sub_head)) {
        c("", paste(rep(g$dv_labels, each = g$per), g$sub_head))
      } else c("", g$dv_labels)
      utils::write.csv(stats::setNames(as.data.frame(m), header), path, row.names = FALSE,
                       fileEncoding = "UTF-8")
    },
    stop(sprintf("Unsupported extension '.%s'. Use .docx, .tex, .html, or .csv.", ext),
         call. = FALSE)
  )
  invisible(path)
}

#' Tidy results as a data frame
#'
#' One row per coefficient, reference level, or contrast per outcome, with
#' the within-factor p-value (`p.within`) and the final reported p-value
#' (`p.value`, after any across-outcome correction).
#'
#' @param x A `clean_results` object.
#' @return A data frame.
#' @export
cr_tidy <- function(x) {
  e <- x$estimates
  e <- e[e$row_type != "header", c("dv", "section", "variable", "level", "term", "label",
                                    "is_ref", "estimate", "std.error", "statistic", "df",
                                    "conf.low", "conf.high", "p.within", "p.value",
                                    "dv_adjusted")]
  e$model_type <- vapply(e$dv, function(d) x$meta[[d]]$type, "")
  e$estimate_type <- vapply(e$dv, function(d) est_symbol(x$meta[[d]]), "")
  rownames(e) <- NULL
  e
}

# Figures: vector PDF (cairo, fonts embedded) or SVG/EPS by default; PNG/TIFF at
# 600 dpi. Widths follow journal columns (figure guide): "1col" 88 mm,
# "1.5col" 125 mm, "2col" 178 mm, or a number in mm.
save_plot <- function(plot, path, width = "1.5col", height = NULL, dpi = 600, ...) {
  w <- if (is.character(width)) {
    if (!width %in% names(.cr_widths)) {
      stop("`width` must be \"1col\", \"1.5col\", \"2col\", or a number in mm.", call. = FALSE)
    }
    unname(.cr_widths[width])
  } else width
  h <- height %||% round(w * 0.65)
  ext <- tolower(tools::file_ext(path))
  device <- switch(ext,
    pdf = grDevices::cairo_pdf,
    eps = grDevices::cairo_ps,
    svg = "svg", png = "png", tiff = , tif = "tiff", jpg = , jpeg = "jpeg",
    stop(sprintf("Unsupported figure format '.%s'. Use .pdf, .svg, .eps, .png, or .tiff.", ext),
         call. = FALSE))
  ggplot2::ggsave(path, plot, width = w, height = h, units = "mm", dpi = dpi, device = device,
                  ...)
}
